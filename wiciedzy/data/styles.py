def P(*values: int) -> dict[str, int]:
    if len(values) != len(DIMENSIONS):
        raise ValueError(f"expected {len(DIMENSIONS)} scores, got {len(values)}")
    return dict(zip(DIMENSIONS, values, strict=True))


def src(
    title: str,
    url: str,
    author: str,
    source_type: str,
    license_name: str = "",
    license_url: str = "",
    role: str = "definition",
    quality: str = "secondary",
) -> dict[str, str]:
    return {
        "title": title,
        "url": url,
        "author": author,
        "source_type": source_type,
        "license": license_name,
        "license_url": license_url,
        "attribution": author,
        "accessed_at": ACCESSED,
        "role": role,
        "quality": quality,
    }


WIKI = "CC BY-SA 4.0"
WIKI_URL = "https://creativecommons.org/licenses/by-sa/4.0/"


def wiki(title: str, url: str, role: str = "definition", quality: str = "secondary") -> dict[str, str]:
    return src(title, url, "Wikipedia contributors", "wikipedia", WIKI, WIKI_URL, role, quality)


def brit(title: str, url: str, role: str = "history", quality: str = "reputable_reference") -> dict[str, str]:
    return src(title, url, "Encyclopaedia Britannica", "encyclopedia", role=role, quality=quality)


def fed(title: str, url: str, author: str, role: str = "current_practice", quality: str = "institutional") -> dict[str, str]:
    return src(title, url, author, "federation", role=role, quality=quality)


def discover(title: str, url: str) -> dict[str, str]:
    """A page that finds the topic, but does not describe the practice itself."""
    return brit(title, url, role="discovery", quality="discovery_only")


