from __future__ import annotations


def _item(
    slug: str,
    skill: str,
    exercise_type: str,
    minutes: int,
    category_en: str,
    category_pl: str,
    title_en: str,
    title_pl: str,
    instructions_en: str,
    instructions_pl: str,
    prompt_en: str,
    prompt_pl: str,
    content_en: str = "",
    content_pl: str = "",
    options: list | None = None,
    source_note: str = "Original Poligon text",
) -> dict:
    row = {
        "slug": slug,
        "skill": skill,
        "level": 2,
        "exercise_type": exercise_type,
        "expected_minutes": minutes,
        "original_content": True,
        "source_note": source_note,
        "title_en": title_en,
        "title_pl": title_pl,
        "category_en": category_en,
        "category_pl": category_pl,
        "instructions_en": instructions_en,
        "instructions_pl": instructions_pl,
        "prompt_en": prompt_en,
        "prompt_pl": prompt_pl,
        "content_en": content_en,
        "content_pl": content_pl,
    }
    if options is not None:
        row["options"] = options
    return row


def _opts(correct: tuple[str, str], *wrongs: tuple[str, str]) -> list[dict]:
    rows = [{"text_en": correct[0], "text_pl": correct[1], "is_correct": True}]
    rows.extend({"text_en": en, "text_pl": pl, "is_correct": False} for en, pl in wrongs)
    return rows


